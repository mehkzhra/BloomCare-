"""Back up or explicitly restore the local Docker PostgreSQL database."""

import argparse
import secrets
import subprocess
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("operation", choices=["backup", "restore", "restore-test"])
    parser.add_argument("--file", type=Path)
    parser.add_argument("--confirm-restore", action="store_true")
    args = parser.parse_args()
    if args.operation == "backup":
        target = args.file or ROOT / "backups" / (
            datetime.now().strftime("BloomCare-%Y%m%d-%H%M%S") + ".dump"
        )
        target = target.resolve()
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            raise SystemExit("Choose a new backup filename; existing files are not overwritten.")
        try:
            with target.open("xb") as stream:
                subprocess.run(
                    [
                        "docker",
                        "compose",
                        "exec",
                        "-T",
                        "db",
                        "sh",
                        "-c",
                        'pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" --format=custom',
                    ],
                    cwd=ROOT,
                    stdout=stream,
                    check=True,
                )
        except subprocess.CalledProcessError:
            target.unlink(missing_ok=True)
            raise SystemExit(
                "Backup failed. Start Docker Desktop and the database first."
            ) from None
        print("Database backup saved:", target)
    elif args.operation == "restore-test":
        if args.file is None or not args.file.is_file():
            raise SystemExit(
                "Restore-test needs an existing --file. The application DB is not changed."
            )
        with args.file.open("rb") as stream:
            if stream.read(5) != b"PGDMP":
                raise SystemExit(
                    "Use a PostgreSQL custom-format backup generated by the backup command."
                )
        target = "bloomcare_restore_test_" + secrets.token_hex(6)
        prefix = [
            "docker",
            "compose",
            "exec",
            "-T",
            "-e",
            "BLOOMCARE_RESTORE_DB=" + target,
            "db",
            "sh",
            "-c",
        ]
        created = False
        try:
            subprocess.run(
                prefix + ['createdb -U "$POSTGRES_USER" "$BLOOMCARE_RESTORE_DB"'],
                cwd=ROOT,
                check=True,
            )
            created = True
            with args.file.open("rb") as stream:
                subprocess.run(
                    prefix
                    + [
                        'pg_restore --exit-on-error --no-owner -U "$POSTGRES_USER" '
                        '-d "$BLOOMCARE_RESTORE_DB"'
                    ],
                    cwd=ROOT,
                    stdin=stream,
                    check=True,
                )
            sql = (
                "SELECT version_num FROM alembic_version; "
                "SELECT count(*) FROM users; SELECT count(*) FROM health_records; "
                "SELECT count(*) FROM doctor_notes; SELECT count(*) FROM medical_reports; "
                "DO $$ BEGIN IF EXISTS (SELECT 1 FROM medical_reports "
                "WHERE octet_length(content) <> byte_size) THEN "
                "RAISE EXCEPTION 'Report byte-size integrity failed'; END IF; END $$;"
            )
            # SQL is fixed source text, never derived from backup content or credentials.
            subprocess.run(
                prefix
                + [
                    'psql --set=ON_ERROR_STOP=1 -U "$POSTGRES_USER" '
                    '-d "$BLOOMCARE_RESTORE_DB" -c "$1"',
                    "bloomcare-restore-check",
                    sql,
                ],
                cwd=ROOT,
                check=True,
                stdout=subprocess.DEVNULL,
            )
        finally:
            if created:
                subprocess.run(
                    prefix + ['dropdb -U "$POSTGRES_USER" "$BLOOMCARE_RESTORE_DB"'],
                    cwd=ROOT,
                    check=True,
                )
        print(
            "Restore-test passed: isolated database restored; core tables/report lengths checked."
        )
        print("Temporary test database removed. The application database was not changed.")
    else:
        if not args.confirm_restore or args.file is None or not args.file.is_file():
            raise SystemExit(
                "Restore needs an existing --file and --confirm-restore. Stop both servers first."
            )
        with args.file.open("rb") as stream:
            subprocess.run(
                [
                    "docker",
                    "compose",
                    "exec",
                    "-T",
                    "db",
                    "sh",
                    "-c",
                    "pg_restore --exit-on-error --clean --if-exists --no-owner "
                    '-U "$POSTGRES_USER" -d "$POSTGRES_DB"',
                ],
                cwd=ROOT,
                stdin=stream,
                check=True,
            )
        print("Database restored. Run migrations and restart the application.")


if __name__ == "__main__":
    main()
